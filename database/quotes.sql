-- Incremental update for an existing AO Nexus Central installation (run once in the Supabase SQL editor;
-- running it again is harmless: saved quotes are never changed or deleted).
-- Enables «Cotizaciones»: quotes for clients with a branded PDF and WhatsApp sharing, visible to the active team.
-- A quote never reserves or discounts stock: the stock drops only when the quote is converted into a receipt
-- («Convertir en boleta») and that receipt is issued. Once its receipt is issued the quote is kept as it was sent
-- (it can be duplicated or deleted); if that receipt is deleted the quote can be edited again.
-- Quote numbers (COT-00012) are assigned by the database on the first save and never change. Saving a quote again,
-- a failed save or a rolled back test does not consume numbers, and the number of a deleted quote is not reused.
create table if not exists public.ao_quotes (
  id uuid primary key,                       -- generated by the app, so a retried save never duplicates a quote
  number bigint not null unique,             -- shown as COT-00012; assigned by ao_private.stamp_quote()
  quote jsonb not null check (jsonb_typeof(quote)='object'),
  customer text not null check (length(btrim(customer)) between 1 and 110),
  document text not null default '' check (length(document)<=20),
  phone text not null default '' check (length(phone)<=20),
  total_cents bigint not null check (total_cents between 0 and 99999999999),
  quote_date date not null,
  valid_until date not null,
  receipt_id uuid,                           -- request ID of the receipt prepared from this quote (= its ao_receipts.id)
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ao_quotes_validity check (valid_until>=quote_date and valid_until<=quote_date+365)
);
create index if not exists ao_quotes_created_at_idx on public.ao_quotes(created_at desc);

-- Transactional counter instead of a sequence: an upsert evaluates sequence defaults even when it ends up
-- updating, so every new save of a quote would skip a number.
create table if not exists ao_private.quote_counter (
  singleton boolean primary key default true check (singleton),
  last_number bigint not null check (last_number>=0)
);
insert into ao_private.quote_counter(singleton,last_number)
  select true,coalesce(max(number),0) from public.ao_quotes
  on conflict (singleton) do update set last_number=greatest(ao_private.quote_counter.last_number,excluded.last_number);

create or replace function ao_private.stamp_quote()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if tg_op='INSERT' then
    -- Saving an existing quote again (upsert) keeps its number; a new quote takes the next one.
    select q.number into new.number from public.ao_quotes q where q.id=new.id;
    if new.number is null then
      update ao_private.quote_counter set last_number=last_number+1 where singleton returning last_number into new.number;
    end if;
    new.created_by:=coalesce(auth.uid(),new.created_by); new.created_at:=now(); new.updated_at:=now();
    return new;
  end if;
  new.number:=old.number; new.created_by:=old.created_by; new.created_at:=old.created_at;
  -- The quote of an issued receipt is the record of that sale: it is duplicated instead of changed.
  if old.receipt_id is not null and (to_jsonb(new)-'updated_at') is distinct from (to_jsonb(old)-'updated_at')
    and exists(select 1 from public.ao_receipts r where r.id=old.receipt_id and r.deleted_at is null) then
    raise exception 'Esta cotización ya se convirtió en una boleta emitida y no se puede modificar. Para cambiar precios, duplícala.';
  end if;
  new.updated_at:=now();
  return new;
end;
$$;
revoke all on function ao_private.stamp_quote() from public,anon,authenticated;
drop trigger if exists ao_quotes_stamp on public.ao_quotes;
create trigger ao_quotes_stamp before insert or update on public.ao_quotes
  for each row execute function ao_private.stamp_quote();

alter table public.ao_quotes enable row level security;
alter table ao_private.quote_counter enable row level security;
revoke all on public.ao_quotes from public,anon,authenticated;
revoke all on ao_private.quote_counter from public,anon,authenticated;
grant select,insert,update,delete on public.ao_quotes to authenticated;
drop policy if exists ao_quotes_team on public.ao_quotes;
create policy ao_quotes_team on public.ao_quotes for all to authenticated
  using((select ao_private.is_member())) with check((select ao_private.is_member()));

notify pgrst,'reload schema';
