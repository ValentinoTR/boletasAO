-- AO Nexus Central. Additive schema; existing boletas remain untouched.
create table public.ao_products (
  id bigint generated by default as identity primary key,
  data jsonb not null check (jsonb_typeof(data) = 'object'),
  web_price numeric(18,2) not null check (web_price >= 0),
  reference_stock integer not null default 0 check (reference_stock >= 0),
  managed boolean not null default false,
  published boolean not null default true,
  updated_at timestamptz not null default now()
);
create table public."COMPRAS" (
  id bigint generated always as identity primary key,
  nombre text not null check (length(nombre) between 1 and 350),
  costo numeric(18,2) not null check (costo >= 0),
  moneda text not null default 'PEN' check (moneda in ('PEN','USD')),
  tipo_cambio numeric(18,6) not null default 0 check (tipo_cambio >= 0),
  impuesto numeric(10,4) not null default 0 check (impuesto >= 0),
  proveedor text, fecha_compra date, numero_pedido text, courier text,
  peso_kg numeric(18,4) not null default 0 check (peso_kg >= 0),
  costo_envio_kg numeric(18,2) not null default 0 check (costo_envio_kg >= 0),
  tax_usa numeric(18,2) not null default 0 check (tax_usa >= 0),
  impuesto_peru numeric(18,2) not null default 0 check (impuesto_peru >= 0),
  otros_gastos numeric(18,2) not null default 0 check (otros_gastos >= 0),
  categoria text, created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users(id),
  source_project text, source_id text,
  unique(source_project, source_id)
);
create table public."COMPONENTES" (
  id bigint generated always as identity primary key,
  compra_id bigint not null references public."COMPRAS"(id) on delete cascade,
  nombre text not null check (length(nombre) between 1 and 350),
  costo numeric(18,2) check (costo >= 0),
  precio_venta numeric(18,2) check (precio_venta >= 0),
  precio_sugerido numeric(18,2) check (precio_sugerido >= 0),
  fecha_venta timestamptz, comprador_nombre text, comprador_documento text,
  product_id bigint references public.ao_products(id),
  receipt_id uuid references public.ao_receipts(id),
  sale_cost numeric(18,2), serial text,
  source_project text, source_id text,
  unique(source_project, source_id)
);
create index ao_components_purchase_idx on public."COMPONENTES"(compra_id);
create index ao_purchases_created_by_idx on public."COMPRAS"(created_by);
create index ao_components_stock_idx on public."COMPONENTES"(product_id) where precio_venta is null;
create index ao_components_receipt_idx on public."COMPONENTES"(receipt_id);
create table public.ao_clients (
  id uuid primary key default gen_random_uuid(),
  name text not null, doc_type text not null, document text not null default '',
  email text, address text, updated_at timestamptz not null default now()
);
create unique index ao_clients_document_idx on public.ao_clients(doc_type, document) where document <> '';
create table public.ao_sales (
  receipt_id uuid primary key references public.ao_receipts(id),
  client_id uuid not null references public.ao_clients(id),
  signature jsonb not null,
  created_at timestamptz not null default now()
