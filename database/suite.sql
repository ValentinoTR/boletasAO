create function ao_private.protect_issued_component() returns trigger language plpgsql security invoker set search_path='' as $$
begin
 if old.receipt_id is not null then
  if tg_op='DELETE' then raise exception 'Esta unidad ya está vinculada a una boleta emitida.'; end if;
  if (to_jsonb(new)-'precio_sugerido') is distinct from (to_jsonb(old)-'precio_sugerido') then raise exception 'Los datos de una venta con boleta emitida se conservan en su historial.'; end if;
 end if;
 if tg_op='DELETE' then return old; end if;
 return new;
end;
$$;
revoke all on function ao_private.protect_issued_component() from public,anon,authenticated;
create trigger protect_issued_component before update or delete on public."COMPONENTES" for each row execute function ao_private.protect_issued_component();

create function ao_private.protect_issued_purchase() returns trigger language plpgsql security invoker set search_path='' as $$
begin
 if exists(select 1 from public."COMPONENTES" where compra_id=old.id and receipt_id is not null) then
  if tg_op='DELETE' then raise exception 'Esta compra incluye unidades con boleta emitida.'; end if;
  if (new.costo,new.moneda,new.tipo_cambio,new.impuesto,new.peso_kg,new.costo_envio_kg,new.tax_usa,new.impuesto_peru,new.otros_gastos)
   is distinct from (old.costo,old.moneda,old.tipo_cambio,old.impuesto,old.peso_kg,old.costo_envio_kg,old.tax_usa,old.impuesto_peru,old.otros_gastos) then
   raise exception 'Los costos de las compras con boletas emitidas se conservan para su historial.';
  end if;
 end if;
 if tg_op='DELETE' then return old; end if;
 return new;
end;
$$;
revoke all on function ao_private.protect_issued_purchase() from public,anon,authenticated;
create trigger protect_issued_purchase before update or delete on public."COMPRAS" for each row execute function ao_private.protect_issued_purchase();

-- Bring the old accountant's authenticated export into this team, once per source id.
create function ao_private.import_accounting(bundle jsonb) returns jsonb language plpgsql security definer set search_path='' as $$
declare p jsonb; c jsonb; purchase bigint; purchase_count integer:=0; component_count integer:=0; n integer;
begin
 if not exists(select 1 from public.ao_members where user_id=auth.uid() and active and role='owner') then raise exception 'Solo el administrador puede importar las compras.' using errcode='42501'; end if;
 if bundle->>'source' is distinct from 'rqoxzaszzvwxpvomfvay' or jsonb_typeof(bundle->'compras') is distinct from 'array' or jsonb_typeof(bundle->'componentes') is distinct from 'array' then raise exception 'Archivo de origen inválido.'; end if;
 if jsonb_array_length(bundle->'compras')>10000 or jsonb_array_length(bundle->'componentes')>50000 then raise exception 'La importación es demasiado grande.'; end if;
 for p in select value from jsonb_array_elements(bundle->'compras') loop
  insert into public."COMPRAS"(nombre,costo,moneda,tipo_cambio,impuesto,proveedor,fecha_compra,numero_pedido,courier,peso_kg,costo_envio_kg,tax_usa,impuesto_peru,otros_gastos,categoria,created_at,created_by,source_project,source_id)
   values(p->>'nombre',(p->>'costo')::numeric,coalesce(p->>'moneda','PEN'),coalesce((p->>'tipo_cambio')::numeric,0),coalesce((p->>'impuesto')::numeric,0),p->>'proveedor',nullif(p->>'fecha_compra','')::date,p->>'numero_pedido',p->>'courier',coalesce((p->>'peso_kg')::numeric,0),coalesce((p->>'costo_envio_kg')::numeric,0),coalesce((p->>'tax_usa')::numeric,0),coalesce((p->>'impuesto_peru')::numeric,0),coalesce((p->>'otros_gastos')::numeric,0),p->>'categoria',coalesce((p->>'created_at')::timestamptz,now()),auth.uid(),'rqoxzaszzvwxpvomfvay',p->>'id') on conflict(source_project,source_id) do nothing;
  get diagnostics n=row_count; purchase_count:=purchase_count+n;
 end loop;
 for c in select value from jsonb_array_elements(bundle->'componentes') loop
  select id into purchase from public."COMPRAS" where source_project='rqoxzaszzvwxpvomfvay' and source_id=c->>'compra_id';
  if purchase is null then raise exception 'Una unidad no tiene su compra de origen.'; end if;
  insert into public."COMPONENTES"(compra_id,nombre,costo,precio_venta,precio_sugerido,fecha_venta,comprador_nombre,comprador_documento,source_project,source_id)
   values(purchase,c->>'nombre',(c->>'costo')::numeric,(c->>'precio_venta')::numeric,(c->>'precio_sugerido')::numeric,(c->>'fecha_venta')::timestamptz,c->>'comprador_nombre',c->>'comprador_documento','rqoxzaszzvwxpvomfvay',c->>'id') on conflict(source_project,source_id) do nothing;
  get diagnostics n=row_count; component_count:=component_count+n;
 end loop;
 insert into public.ao_suite_state values('legacy_import',jsonb_build_object('imported',true,'at',now())) on conflict(key) do update set value=excluded.value;
 return jsonb_build_object('compras',purchase_count,'componentes',component_count);
end;
$$;
revoke all on function ao_private.import_accounting(jsonb) from public,anon;
grant execute on function ao_private.import_accounting(jsonb) to authenticated;
