create function public.ao_component_cost(component_key bigint) returns numeric language sql stable security invoker set search_path='' as $$
 select round(coalesce(c.costo,
   greatest(0, (case when p.moneda='USD' then p.costo*p.tipo_cambio else p.costo end)*(1+p.impuesto/100)
     + p.peso_kg*p.costo_envio_kg+p.tax_usa+p.impuesto_peru+p.otros_gastos
     - coalesce((select sum(x.costo) from public."COMPONENTES" x where x.compra_id=p.id and x.costo is not null),0))
     / greatest(1,(select count(*) from public."COMPONENTES" x where x.compra_id=p.id and x.costo is null))
 ),2) from public."COMPONENTES" c join public."COMPRAS" p on p.id=c.compra_id where c.id=component_key;
$$;
revoke all on function public.ao_component_cost(bigint) from public,anon;
grant execute on function public.ao_component_cost(bigint) to authenticated;

