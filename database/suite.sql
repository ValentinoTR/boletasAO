create function ao_private.link_stock(product_key bigint,unit_keys bigint[],expected_stock integer) returns integer language plpgsql security definer set search_path='' as $$
declare actual integer;
begin
 if not ao_private.is_member() then raise exception 'Acceso no autorizado.' using errcode='42501'; end if;
 perform id from public.ao_products where id=product_key for update;
 if not found then raise exception 'Producto inexistente.'; end if;
 if coalesce(array_length(unit_keys,1),0)>10000 then raise exception 'Demasiadas unidades.'; end if;
 perform c.id from public."COMPONENTES" c where c.id=any(unit_keys) order by c.id for update;
 if exists(select 1 from public."COMPONENTES" where id=any(unit_keys) and (precio_venta is not null or (product_id is not null and product_id<>product_key))) then raise exception 'Selecciona unidades disponibles que no estén vinculadas a otro producto.'; end if;
 if (select count(*) from public."COMPONENTES" where id=any(unit_keys))<>(select count(distinct x) from unnest(unit_keys) x) then raise exception 'Una unidad seleccionada ya no existe.'; end if;
 update public."COMPONENTES" set product_id=product_key where id=any(unit_keys);
 select count(*) into actual from public."COMPONENTES" where product_id=product_key and precio_venta is null;
 if actual<>expected_stock then raise exception 'El stock cambió durante la vinculación. Revisa las unidades antes de confirmar.'; end if;
 update public.ao_products set managed=true,updated_at=now() where id=product_key;
 return actual;
end;
$$;
revoke all on function ao_private.link_stock(bigint,bigint[],integer) from public,anon;
grant execute on function ao_private.link_stock(bigint,bigint[],integer) to authenticated;
create function public.ao_suite_link_stock(product_key bigint,unit_keys bigint[],expected_stock integer) returns integer language sql security invoker set search_path='' as $$ select ao_private.link_stock(product_key,unit_keys,expected_stock); $$;
revoke all on function public.ao_suite_link_stock(bigint,bigint[],integer) from public,anon;
